package api.payload;

public class Pet {
	
	int id;
	String name;
	String petStatus;
	
	
	
	public int getId() {
		return id;
	}
	public void setId(int id) {
		this.id = id;
	}
	public String getName() {
		return name;
	}
	public void setName(String name) {
		this.name = name;
	}
	public String getPetStatus() {
		return petStatus;
	}
	public void setPetStatus(String string) {
		this.petStatus = string;
	}
	

}
